/** 用 vars 填模板。只替换 vars 里有的变量，其余 {{...}} 原样保留。 */
export function fill(tpl, vars) {
    return String(tpl ?? '').replace(/\{\{\s*([^{}\s]+)\s*\}\}/g, (m, key) => {
        if (Object.prototype.hasOwnProperty.call(vars, key)) {
            const v = vars[key];
            return v == null ? '' : String(v);
        }
        return m;
    }).replace(/\n{3,}/g, '\n\n');
}

/** 把规则库展开成 rules.名称 变量 */
export function ruleVars(rules) {
    const out = {};
    for (const [k, v] of Object.entries(rules ?? {})) out[`rules.${k}`] = v;
    return out;
}
